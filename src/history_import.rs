    #[ignore = "explicit million-row import stress regression"]
    fn million_row_import_and_renamed_repeat_are_idempotent() {
        let temp = tempfile::tempdir().unwrap();
        let current = temp.path().join("current.sqlite3");
        let source = temp.path().join("source.sqlite3");
        let src = CollectorDb::open(&source).unwrap();
        src.conn.execute_batch(&format!("BEGIN; WITH RECURSIVE seq(n) AS(SELECT 0 UNION ALL SELECT n+1 FROM seq WHERE n<999999) INSERT INTO events SELECT 28000000+n,n%2,CASE WHEN n%2=1 THEN {PHYSICAL_CODE_BASE} ELSE 1 END,1 FROM seq;
            DELETE FROM lifetime_totals; INSERT INTO lifetime_totals SELECT dev,sum(cnt) FROM events GROUP BY dev;
            INSERT INTO daily_totals SELECT date(bucket*60,'unixepoch','localtime'),dev,sum(cnt) FROM events GROUP BY 1,2;
            INSERT INTO historical_key_totals SELECT 0,code,sum(cnt) FROM events WHERE dev=1 GROUP BY code;
            INSERT INTO native_key_totals SELECT code-{PHYSICAL_CODE_BASE},sum(cnt) FROM events WHERE dev=1 GROUP BY code; COMMIT;")).unwrap();
        let mut dest = CollectorDb::open(&current).unwrap();
        let start = std::time::Instant::now();
        assert_eq!(
            dest.import_history(&source, &current)
                .unwrap()
                .added
                .total(),
            1_000_000
        );
        let first = start.elapsed();
        let repeat = std::time::Instant::now();
        assert_eq!(
            dest.import_history(&source, &current)
                .unwrap()
                .added
                .total(),
            0
        );
        let alias = temp.path().join("renamed-backup.sqlite3");
        storage::backup_connection(&src.conn, &alias).unwrap();
        assert_eq!(
            dest.import_history(&alias, &current).unwrap().added.total(),
            0
        );
        assert_eq!(
            dest.lifetime().unwrap(),
            Counts {
                keyboard: 500_000,
                mouse: 500_000
            }
        );
        assert_eq!(
            dest.conn
                .query_row("SELECT count(*) FROM events WHERE cnt!=1", [], |r| r
                    .get::<_, i64>(0))
                .unwrap(),
            0
        );
        assert_eq!(
            dest.conn
                .query_row("PRAGMA integrity_check", [], |r| r.get::<_, String>(0))
                .unwrap(),
            "ok"
        );
        println!(
            "million rows: initial={first:?}, repeat+renamed={:?}",
            repeat.elapsed()
        );
    }
