    #[test]
    fn multiple_files_and_import_orders_match_per_minute_maxima() {
        use std::collections::BTreeMap;
        let temp = tempfile::tempdir().unwrap();
        let mut expected = BTreeMap::<(i64, i64, i64), i64>::new();
        let mut paths = Vec::new();
        for version in 0..4 {
            let path = temp.path().join(format!("source-{version}.sqlite3"));
            let mut db = CollectorDb::open(&path).unwrap();
            let mut events = Vec::new();
            for minute in 0..80 {
                for (device, dev, code) in [(Device::Keyboard, 1, 0), (Device::Mouse, 0, 1)] {
                    let count = (minute * 3 + dev * 7 + version * 5) % 13;
                    let bucket = 28_000_000 + minute;
                    expected
                        .entry((
                            bucket,
                            dev,
                            if dev == 1 {
                                PHYSICAL_CODE_BASE + code
                            } else {
                                code
                            },
                        ))
                        .and_modify(|v| *v = (*v).max(count))
                        .or_insert(count);
                    events.extend((0..count).map(|_| InputEvent {
                        ts_ms: bucket * 60_000,
                        device,
                        code: code as u32,
                    }));
                }
            }
            db.insert(&events).unwrap();
            paths.push(path);
        }
        for order in [[0, 1, 2, 3], [3, 2, 1, 0], [1, 3, 0, 2]] {
            let current = temp.path().join(format!("dest-{}.sqlite3", order[0]));
            let mut db = CollectorDb::open(&current).unwrap();
            for index in order {
                db.import_history(&paths[index], &current).unwrap();
            }
            for path in &paths {
                assert_eq!(db.import_history(path, &current).unwrap().added.total(), 0);
            }
            let mut counts = Counts::default();
            for (&(bucket, dev, code), &count) in &expected {
                let actual=db.conn.query_row("SELECT COALESCE((SELECT cnt FROM events WHERE bucket=?1 AND dev=?2 AND code=?3),0)",params![bucket,dev,code],|r|r.get::<_,i64>(0)).unwrap();
                assert_eq!(actual, count);
                counts.add(dev, count);
            }
            assert_eq!(db.lifetime().unwrap(), counts);
            assert_eq!(
                db.conn
                    .query_row("SELECT sum(cnt) FROM daily_totals", [], |r| r
                        .get::<_, i64>(0))
                    .unwrap(),
                counts.total()
            );
            for table in ["historical_key_totals", "native_key_totals"] {
                assert_eq!(
                    db.conn
                        .query_row(&format!("SELECT sum(cnt) FROM {table}"), [], |r| r
                            .get::<_, i64>(0))
                        .unwrap(),
                    counts.keyboard
                );
            }
        }
    }

