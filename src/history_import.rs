    #[test]
    fn cleanup_failure_after_commit_does_not_report_the_merge_as_failed() {
        unsafe extern "C" fn deny_temp_drop(
            _: *mut std::ffi::c_void,
            action: i32,
            _: *const std::ffi::c_char,
            _: *const std::ffi::c_char,
            _: *const std::ffi::c_char,
            _: *const std::ffi::c_char,
        ) -> i32 {
            if action == rusqlite::ffi::SQLITE_DROP_TEMP_TABLE {
                rusqlite::ffi::SQLITE_DENY
            } else {
                rusqlite::ffi::SQLITE_OK
            }
        }
        let temp = tempfile::tempdir().unwrap();
        let current = temp.path().join("current.sqlite3");
        let source = temp.path().join("source.sqlite3");
        let mut dest = CollectorDb::open(&current).unwrap();
        let mut src = CollectorDb::open(&source).unwrap();
        add(&mut src, 3, 2, chrono::Local::now().timestamp_millis());
        // SQLite's authorizer injects a real post-commit temporary-table cleanup failure.
        unsafe {
            assert_eq!(
                rusqlite::ffi::sqlite3_set_authorizer(
                    dest.conn.handle(),
                    Some(deny_temp_drop),
                    std::ptr::null_mut()
                ),
                rusqlite::ffi::SQLITE_OK
            );
        }
        assert_eq!(
            dest.import_history(&source, &current)
                .unwrap()
                .added
                .total(),
            5
        );
        assert_eq!(dest.lifetime().unwrap().total(), 5);
        unsafe {
            assert_eq!(
                rusqlite::ffi::sqlite3_set_authorizer(
                    dest.conn.handle(),
                    None,
                    std::ptr::null_mut()
                ),
                rusqlite::ffi::SQLITE_OK
            );
        }
        assert_eq!(
            dest.import_history(&source, &current)
                .unwrap()
                .added
                .total(),
            0
        );
    }

